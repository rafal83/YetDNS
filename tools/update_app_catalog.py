def generate(snapshot):
    services = snapshot['services']
    assert len(services) <= 64
    domains = {}
    lines = ['// Generated by tools/update_app_catalog.py; NextDNS data, MIT license.',
             '// Source revision: ' + snapshot['revision'], 'static const Application catalog[] = {']
    for index, service in enumerate(services):
        assert service['id'] == SERVICES[index][0], 'Do not change persistent bit positions'
        fields = ', '.join(json.dumps(service[key], ensure_ascii=False) for key in ('id', 'name', 'category'))
        lines.append('    {' + fields + ', ' + str(len(service['domains'])) + '},')
        for domain in service['domains']:
            assert len(domain) <= 253 and all(re.fullmatch(r'[a-z0-9_-]{1,63}', label) for label in domain.split('.')), domain
            domains[domain] = domains.get(domain, 0) | (1 << index)
    lines += ['};', 'struct AppDomain { const char *name; uint64_t mask; };', 'static const AppDomain app_domains[] = {']
    lines += ['    {' + json.dumps(domain) + ', UINT64_C(0x' + format(mask, 'x') + ')},' for domain, mask in sorted(domains.items())]
    lines += ['};', '']
    (ROOT / 'main/app_catalog.inc').write_text('\n'.join(lines), encoding='utf-8')
    print(len(services), 'services,', len(domains), 'distinct domain suffixes')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--offline', action='store_true', help='Regenerate C++ from the checked-in JSON')
    parser.add_argument('--ref', default='main', help='NextDNS revision or branch to snapshot')
    args = parser.parse_args()
    target = ROOT / 'data/applications.json'
    if args.offline:
        snapshot = json.loads(target.read_text(encoding='utf-8'))
    else:
        def fetch(url):
            with urllib.request.urlopen(url, timeout=30) as response:
                return response.read().decode('utf-8')
        commit = json.loads(fetch('https://api.github.com/repos/nextdns/services/commits/' + args.ref))['sha']
        base = 'https://raw.githubusercontent.com/nextdns/services/' + commit + '/'
        def service_data(meta):
            ident, name, category = meta
            lines = [line.split('#', 1)[0].strip().lower().rstrip('.') for line in fetch(base + 'services/' + ident).splitlines()]
            domains = sorted(set(line for line in lines if line))
            assert domains
            return dict(id=ident, name=name, category=category, domains=domains)
        with ThreadPoolExecutor(max_workers=6) as executor:
            services = list(executor.map(service_data, SERVICES))
        snapshot = dict(source='https://github.com/nextdns/services', revision=commit, license='MIT', services=services)
        license_text = fetch(base + 'LICENSE')
        generate(snapshot)  # Validate before replacing the public snapshot.
        target.write_text(json.dumps(snapshot, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        (ROOT / 'data/nextdns-services-LICENSE.txt').write_text(license_text, encoding='utf-8')
    generate(snapshot)


if __name__ == '__main__':
    main()
